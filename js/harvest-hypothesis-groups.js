/**
 * Harvest pool ↔ hypothesis groups.
 *
 * Contacts get a best-fit hypothesis group when the ChatGPT categorization JSON is imported
 * (Bulk Group Assignment / My Leads). It is stored on each contact as
 * heyreach_contacts.hypothesisFit = { groupId, groupName, score, ... }.
 *
 * Inside the harvest pool every hypothesis group is split in two:
 *   - "gen": connections WE generated (HeyReach CONNECTION_REQUEST_ACCEPTED on the seat, or a manual
 *            "Pando Executive Networking originated" label). connectionOrigin = 'heyreach' | 'healthluminate'
 *   - "pre": connections the executive ALREADY had (not generated by Pando / HealthLuminate).
 *            connectionOrigin = 'pre_existing'
 *
 * Used by harvest_pool.html and harvest_pool_admin.html (generate_messages.html has its own copy of the
 * same rules, with the same values "hyp:gen:<groupId>" / "hyp:pre:<groupId>" in its Group dropdown).
 *
 * Requires window.clemailFirestore (clemail-firestore-wrapper.js). The caller passes in
 * { railway, authHeaders } for the eligible-contacts endpoint that provides connectionOrigin.
 */
(function () {
    'use strict';

    const CONTACT_FIELDS = ['accountEmail', 'bdrEmail', 'linkedin_url', 'profileUrl', 'leadProfileUrl', 'linkedInUrl', 'hypothesisFit', 'leadCategory'];
    /** Lead categories that are never worked (same list as Generate Messages). */
    const SKIP_CATEGORIES = ['Exclude', 'Manual Manage'];
    const GEN_LABEL = 'Generated through Pando';
    const PRE_LABEL = 'Already connected (not by Pando)';

    function normUrl(url) {
        if (!url) return '';
        return String(url).trim().toLowerCase().split('?')[0].split('#')[0]
            .replace(/\/+$/, '').replace(/^https?:\/\/(www\.)?/, '');
    }

    const isPreExisting = (origin) => origin === 'pre_existing';
    /** 'not_verified' only occurs in uploaded-URL mode; it is not something we can say we generated. */
    const isNotOurs = (origin) => origin === 'pre_existing' || origin === 'not_verified';

    let linkedInEmailMap = null; // authEmail -> linkedInEmail
    async function ensureEmailMap() {
        if (linkedInEmailMap) return linkedInEmailMap;
        linkedInEmailMap = new Map();
        try {
            const { collection, getDocs } = window.clemailFirestore;
            const db = window.clemailFirestore.db || window.clemailDb;
            const snap = await getDocs(collection(db, 'linkedin_email_associations'));
            snap.forEach((d) => {
                const x = d.data() || {};
                if (x.authEmail && x.linkedInEmail) linkedInEmailMap.set(x.authEmail, x.linkedInEmail);
            });
        } catch (e) { console.warn('[harvest-hypothesis] linkedin_email_associations:', e && e.message); }
        return linkedInEmailMap;
    }

    function emailVariants(bdrEmail, map) {
        const lower = String(bdrEmail || '').toLowerCase();
        let li = map.get(bdrEmail) || null;
        if (!li) for (const [a, l] of map) { if ((a || '').toLowerCase() === lower) { li = l; break; } }
        return [...new Set([bdrEmail, lower, li, li && li.toLowerCase()].filter(Boolean))];
    }

    function select(q, fields) {
        return q && typeof q.select === 'function' ? q.select(...fields) : q;
    }

    /** Map<normalizedUrl, { groupId, groupName, score }> for every categorized contact of this BDR. */
    async function loadFits(bdrEmail) {
        const map = await ensureEmailMap();
        const { collection, query, where, getDocs } = window.clemailFirestore;
        const db = window.clemailFirestore.db || window.clemailDb;
        const fits = new Map();
        const jobs = [];
        for (const email of emailVariants(bdrEmail, map)) {
            for (const field of ['accountEmail', 'bdrEmail', 'linkedInAccountEmail']) {
                jobs.push(
                    getDocs(select(query(collection(db, 'heyreach_contacts'), where(field, '==', email)), CONTACT_FIELDS), { timeoutMs: 60000 })
                        .then((snap) => snap.forEach((d) => {
                            const x = d.data() || {};
                            const fit = x.hypothesisFit && typeof x.hypothesisFit === 'object' && x.hypothesisFit.groupId ? x.hypothesisFit : null;
                            if (!fit) return;
                            const n = normUrl(x.profileUrl || x.linkedin_url || x.leadProfileUrl || x.linkedInUrl || '');
                            if (n) fits.set(n, { groupId: fit.groupId, groupName: fit.groupName || fit.groupId, score: fit.score == null ? null : fit.score, leadCategory: x.leadCategory || '' });
                        }))
                        .catch((e) => console.warn('[harvest-hypothesis] heyreach_contacts', field, email, e && e.message))
                );
            }
        }
        await Promise.all(jobs);
        return fits;
    }

    /** Eligible harvest pool contacts (carry connectionOrigin) from Railway. */
    async function loadPoolContacts(bdrEmail, ctx, poolId, wholePool) {
        const h = await ctx.authHeaders();
        // applyEngagement=false: counts must not shrink just because a contact is marked Do Not Engage.
        let url = `${ctx.railway}/api/connect/harvest-pool/eligible-contacts/${encodeURIComponent(bdrEmail)}?excludeRecentDays=0&applyEngagement=false`;
        if (wholePool) url += '&minDaysSinceConnection=0'; // every connection the server knows how it was made, not only the "old enough" ones
        if (poolId) url += `&poolId=${encodeURIComponent(poolId)}`;
        const r = await fetch(url, { headers: h });
        const j = await r.json();
        if (!j.success) throw new Error(j.error || 'Could not load harvest pool contacts');
        return j.contacts || [];
    }

    /** Normalized URLs the admin excluded from the harvest pool (manual label originType 'excluded'). */
    async function loadExcludedUrls(bdrEmail, ctx) {
        const out = new Set();
        try {
            const h = await ctx.authHeaders();
            const r = await fetch(`${ctx.railway}/api/connect/harvest-pool/manual-contacts/${encodeURIComponent(bdrEmail)}`, { headers: h });
            const j = await r.json();
            if (!j.success) throw new Error(j.error || 'failed');
            (j.entries || []).forEach((e) => { if (e && e.originType === 'excluded') out.add(normUrl(e.linkedInUrl || e.normalizedUrl)); });
        } catch (e) { console.warn('[harvest-hypothesis] exclusion list:', e && e.message); }
        return out;
    }

    /**
     * Hypothesis groups for a BDR's harvest pool, each split into gen / pre.
     * @returns {Promise<{ groups: Array<{groupId,name,gen,pre,total,genUrls:Set,preUrls:Set}>,
     *                     uncategorized:{gen:number,pre:number}, poolSize:number }>}
     * Only contacts that are in the harvest pool are counted.
     */
    async function loadPools(bdrEmail, ctx, poolId) {
        // A specific pool selection only lists that pool's members; "already connected" people belong to no pool.
        const withOutside = !poolId;
        const [contacts, fits, known, excluded] = await Promise.all([
            loadPoolContacts(bdrEmail, ctx, poolId, false),
            loadFits(bdrEmail),
            withOutside ? loadPoolContacts(bdrEmail, ctx, '', true) : Promise.resolve([]),
            withOutside ? loadExcludedUrls(bdrEmail, ctx) : Promise.resolve(new Set())
        ]);
        const groups = new Map();
        const uncategorized = { gen: 0, pre: 0 };
        const addToGroup = (n, fit, side) => {
            let g = groups.get(fit.groupId);
            if (!g) { g = { groupId: fit.groupId, name: fit.groupName, gen: 0, pre: 0, total: 0, genUrls: new Set(), preUrls: new Set() }; groups.set(fit.groupId, g); }
            g[side]++; g.total++;
            g[side + 'Urls'].add(n);
        };
        const poolUrls = new Set();
        contacts.forEach((c) => {
            const n = normUrl(c.linkedInUrl);
            poolUrls.add(n);
            const side = isPreExisting(c.connectionOrigin) ? 'pre' : 'gen';
            const fit = fits.get(n);
            if (!fit) { uncategorized[side]++; return; }
            addToGroup(n, fit, side);
        });

        // Categorized connections the server never put in the pool (no HeyReach accept / manual label on file):
        // these are the people the executive already had. They are the "Previous Connections".
        let outsidePool = 0;
        if (withOutside) {
            const knownUrls = new Set(known.map((c) => normUrl(c.linkedInUrl)));
            fits.forEach((fit, n) => {
                if (poolUrls.has(n) || knownUrls.has(n) || excluded.has(n) || SKIP_CATEGORIES.includes(fit.leadCategory)) return;
                addToGroup(n, fit, 'pre');
                outsidePool++;
            });
        }
        return {
            groups: [...groups.values()].sort((a, b) => a.name.localeCompare(b.name)),
            uncategorized,
            poolSize: contacts.length,
            outsidePool,            // categorized "Previous Connections" that are not in the harvest pool itself
            contacts,
            fits
        };
    }

    /**
     * Fill a <select> with two sections of hypothesis groups. Option values are
     * "hyp:gen:<groupId>" and "hyp:pre:<groupId>" (same as Generate Messages).
     * @param {HTMLSelectElement} sel
     * @param {Array} groups from loadPools().groups
     * @param {string} firstLabel text of the empty "no filter" option
     */
    function fillSelect(sel, groups, firstLabel) {
        if (!sel) return;
        const keep = sel.value;
        sel.innerHTML = '';
        const first = document.createElement('option');
        first.value = ''; first.textContent = firstLabel || 'All contacts (no hypothesis group filter)';
        sel.appendChild(first);
        const section = (mode, label) => {
            const items = (groups || []).filter((g) => g[mode] > 0);
            if (!items.length) return;
            const og = document.createElement('optgroup');
            og.label = label;
            items.forEach((g) => {
                const o = document.createElement('option');
                o.value = `hyp:${mode}:${g.groupId}`;
                o.textContent = `${g.name} (${g[mode]})`;
                og.appendChild(o);
            });
            sel.appendChild(og);
        };
        section('gen', '🧬 Hypothesis groups — ' + GEN_LABEL + ' (our connections)');
        section('pre', '🧬 Hypothesis groups — ' + PRE_LABEL);
        if (keep && [...sel.options].some((o) => o.value === keep)) sel.value = keep;
    }

    /** 'hyp:gen:<id>' -> { mode, groupId } (null for anything else). */
    function parseValue(value) {
        const m = /^hyp:(gen|pre):(.+)$/.exec(String(value || ''));
        return m ? { mode: m[1], groupId: m[2] } : null;
    }

    /** Does a pool contact belong to the selected dropdown value? (fits comes from loadPools()). */
    function contactMatches(contact, value, fits) {
        const p = parseValue(value);
        if (!p) return true;
        const fit = fits && fits.get(normUrl(contact.linkedInUrl));
        if (!fit || fit.groupId !== p.groupId) return false;
        return p.mode === 'pre' ? isPreExisting(contact.connectionOrigin) : !isPreExisting(contact.connectionOrigin);
    }

    window.HarvestHypothesis = { normUrl, isNotOurs, isPreExisting, loadPools, fillSelect, parseValue, contactMatches, GEN_LABEL, PRE_LABEL };
})();
